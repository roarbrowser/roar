// Agent sessions as chat (mcp/agent-chat.mjs): transcript parsing and the role filter, linking a session
// to its transcript, activity chips and approval prompts. scripts/test-agent-chat.sh. No CEF, no tmux.
import { mkdtempSync, mkdirSync, writeFileSync, utimesSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';
import { slug, pickTranscript, transcriptFor, parseClaude, parseCodex, summarize, approvalPrompt, busy, chat } from '../mcp/agent-chat.mjs';

let fail = 0;
const check = (ok, what) => { if (!ok) fail++; console.log((ok ? 'ok   ' : 'FAIL ') + what); };
const jl = (...rows) => rows.map((r) => JSON.stringify(r)).join('\n') + '\n';
const user = (content, extra = {}) => ({ type: 'user', message: { role: 'user', content }, timestamp: '2026-10-18T10:00:00Z', ...extra });
const asst = (content, extra = {}) => ({ type: 'assistant', message: { role: 'assistant', content }, ...extra });

// Slug: every non-alphanumeric folds to '-'.
check(slug('/Users/x/a_b.c/d-e') === '-Users-x-a-b-c-d-e', 'slug folds / _ . to -');

// Role filter: only words a human typed become the user's bubbles.
const items = parseClaude(jl(
  user('fix the sidebar'),
  user('<system-reminder>\nYou are in plan mode\n</system-reminder>'),
  user([{ type: 'text', text: '<task-notification>agent done</task-notification>' }]),
  user([{ type: 'tool_result', tool_use_id: 't1', content: 'file contents' }]),
  user('<command-name>/clear</command-name>'),
  user('<local-command-stdout>ok</local-command-stdout>'),
  user('<user-prompt-submit-hook>hook says hi</user-prompt-submit-hook>'),
  user('Caveat: The messages below were generated by the user while running local commands.'),
  user('[Request interrupted by user]'),
  user('This session is being continued from a previous conversation.'),
  user('a meta line', { isMeta: true }),
  user('summary', { isCompactSummary: true }),
  user('subagent prompt', { isSidechain: true }),
  asst([{ type: 'text', text: 'subagent reply' }], { isSidechain: true }),
  asst([{ type: 'thinking', thinking: 'hmm' }, { type: 'text', text: 'Looking now.' }]),
  asst([{ type: 'tool_use', name: 'Read', input: { file_path: '/r/a.js' } }]),
  asst([{ type: 'tool_use', name: 'Read', input: { file_path: '/r/b.js' } }]),
  user([{ type: 'tool_result', tool_use_id: 't2', content: '<system-reminder>x</system-reminder>' }]),
  asst([{ type: 'tool_use', name: 'Bash', input: { command: 'ls' } }]),
  asst([{ type: 'text', text: 'Done. **All good.**' }]),
  'not json',
  { type: 'summary', summary: 'x' },
));
const users = items.filter((x) => x.kind === 'user').map((x) => x.text);
check(users.length === 1 && users[0] === 'fix the sidebar', `only the typed prompt is a user bubble (${JSON.stringify(users)})`);
check(!JSON.stringify(items).includes('subagent'), 'sidechain turns skipped');
check(!JSON.stringify(items).includes('hmm'), 'thinking blocks skipped');
check(items.map((x) => x.kind).join() === 'user,assistant,tools,assistant', `order: ${items.map((x) => x.kind)}`);
check(items[2].calls.length === 3, 'consecutive tool calls collapse into one chip, across tool_result turns');
check(items[0].at === '2026-10-18T10:00:00Z', 'timestamp kept');

const pasted = parseClaude(jl(user('\n\n<pasted_content id="ab12">\nfix the bug\nplease\n</pasted_content id="ab12">\n')));
check(pasted.length === 1 && pasted[0].kind === 'user' && pasted[0].text === 'fix the bug\nplease', 'a pasted reply shows as the user\'s words');

// Codex rollout: its injected context is dropped too; patches name their file.
const cx = parseCodex(jl(
  { type: 'session_meta', payload: { id: 's' } },
  { type: 'response_item', payload: { type: 'message', role: 'user', content: [{ type: 'input_text', text: '<environment_context>\n<cwd>/x</cwd>' }] } },
  { type: 'response_item', payload: { type: 'message', role: 'developer', content: [{ type: 'input_text', text: 'rules' }] } },
  { type: 'response_item', payload: { type: 'message', role: 'user', content: [{ type: 'input_text', text: 'add a test' }] } },
  { type: 'response_item', payload: { type: 'function_call', name: 'exec_command', arguments: '{"cmd":"ls"}' } },
  { type: 'response_item', payload: { type: 'custom_tool_call', name: 'apply_patch', input: '*** Begin Patch\n*** Update File: src/x.c\n@@' } },
  { type: 'response_item', payload: { type: 'message', role: 'assistant', content: [{ type: 'output_text', text: 'Added.' }] } },
));
check(cx.map((x) => x.kind).join() === 'user,tools,assistant' && cx[0].text === 'add a test', `codex: ${JSON.stringify(cx.map((x) => x.kind))}`);
check(summarize(cx[1].calls) === 'Edited x.c, ran a command', `codex chip: ${summarize(cx[1].calls)}`);

// Chips.
const S = (...c) => summarize(c.map(([tool, input = {}]) => ({ tool, input })));
check(S(['Read', { file_path: '/a/x.js' }], ['Read', { file_path: '/a/y.js' }], ['Read', { file_path: '/a/z.js' }]) === 'Read 3 files', 'Read 3 files');
check(S(['Bash', { command: 'ls' }]) === 'Ran a command', 'Ran a command');
check(S(['Edit', { file_path: '/a/sidebar.html' }], ['Edit', { file_path: '/a/sidebar.html' }]) === 'Edited sidebar.html', 'Edited sidebar.html (same file twice)');
check(S(['Read', { file_path: '/a/x' }], ['Bash'], ['Bash'], ['Grep'], ['mcp__roar__click']) === 'Read x, ran 2 commands, searched the code, used roar', `mixed: ${S(['Read', { file_path: '/a/x' }], ['Bash'], ['Bash'], ['Grep'], ['mcp__roar__click'])}`);

// Linking by birth time. born: when the CLI process started (ms).
const T = 1_000_000_000_000;
const files = [
  { path: '/p/old.jsonl', born: T - 3600e3, mod: T + 500e3 },   // Another session in the same folder, written to last.
  { path: '/p/mine.jsonl', born: T + 4e3, mod: T + 100e3 },     // Born just after our process.
  { path: '/p/early.jsonl', born: T - 30e3, mod: T + 10e3 },    // Within the 90 s slack, but older than mine.
];
check(pickTranscript(files, { born: T }) === '/p/mine.jsonl', 'newest born at/after the process wins, not newest mtime');
check(pickTranscript(files.filter((f) => f.path !== '/p/mine.jsonl'), { born: T }) === '/p/early.jsonl', '90 s slack before the process start');
check(pickTranscript(files, {}) === '/p/old.jsonl', 'no process start: newest mtime');
check(pickTranscript([{ path: '/p/old.jsonl', born: T - 3600e3, mod: T }], { born: T }) === '/p/old.jsonl', 'none born after: falls back to mtime');
check(pickTranscript([...files, { path: '/p/abc.jsonl', born: 0, mod: 0 }], { sid: 'abc', born: T }) === '/p/abc.jsonl', 'the hook session id names the file exactly');
check(pickTranscript([], { born: T }) === '', 'no transcripts');

// End to end over real files: chat() finds the transcript in <CLAUDE_CONFIG_DIR>/projects/<slug>/.
const CFG = mkdtempSync(join(tmpdir(), 'roar-chat-')), cwd = '/w/my_proj.x', dir = join(CFG, 'projects', slug(cwd));
mkdirSync(dir, { recursive: true });
writeFileSync(join(dir, 'other.jsonl'), jl(user('not mine')));
writeFileSync(join(dir, 'mine.jsonl'), jl(user('hello'), asst([{ type: 'tool_use', name: 'Read', input: { file_path: '/a/q.md' } }])));
utimesSync(join(dir, 'other.jsonl'), new Date(), new Date(Date.now() + 60e3));  // Newer mtime than mine.
process.env.CLAUDE_CONFIG_DIR = CFG;
const born = Date.now() - 5e3;  // Both files were born after this, so the session id picks.
const out = chat({ tool: 'claude', cwd, sid: 'mine' }, born, '', (t, i) => `${t} ${i.file_path}`);
check(out.supported && out.items[0].text === 'hello' && out.items[1].summary === 'Read q.md' && out.items[1].details[0] === 'Read /a/q.md', `chat() end to end (${JSON.stringify(out.items)})`);
check(!chat({ tool: 'gemini', cwd }, 0, '').supported, 'gemini: not supported, falls back to the terminal');

// Approval prompts on screen.
const claudePerm = `
 Bash command
   rm -rf build
 Do you want to proceed?
 ❯ 1. Yes
   2. Yes, and don't ask again for rm commands in /w
   3. No, and tell Claude what to do differently (esc)
`;
const p = approvalPrompt(claudePerm);
check(p?.question === 'Do you want to proceed?' && p.options.length === 3 && p.options[0].key === '1' && p.options[2].label.startsWith('No'), `Claude permission prompt -> 3 buttons (${JSON.stringify(p)})`);
const boxed = '╭──────╮\n│ Allow edit to x.c? │\n│ ❯ 1. Yes │\n│   2. No │\n╰──────╯\n';
check(approvalPrompt(boxed)?.options.map((o) => o.label).join() === 'Yes,No', 'boxed prompt: border characters stripped');
check(approvalPrompt('Here is the plan:\n1. Read files\n2. Edit them\n3. Test\n> ') === null, 'numbered prose without a selection marker is not a prompt');
check(approvalPrompt('Overwrite file? (y/n)')?.options.map((o) => o.key).join() === 'y,n', 'y/n prompt');
check(approvalPrompt('Use 1 of these\n❯ 2. Skip\n  3. Go') === null, 'options must count from 1');
check(approvalPrompt('') === null, 'empty screen');
check(busy('✻ Thinking… (3s · esc to interrupt)') && !busy('> \n? for shortcuts'), 'busy reads "esc to interrupt"');

{
  // The session cd'd away from where it started: its transcript stays in the starting cwd's folder.
  const d = join(CFG, 'projects', slug('/a/start'));
  mkdirSync(d, { recursive: true }); writeFileSync(join(d, 'sid1.jsonl'), '');
  check(transcriptFor({ tool: 'claude', sid: 'sid1', cwd: '/a/start/.claude' }) === join(d, 'sid1.jsonl'), 'transcript found after a cd');
}

console.log(fail ? `${fail} failure(s)` : 'ok');
process.exit(fail ? 1 : 0);
